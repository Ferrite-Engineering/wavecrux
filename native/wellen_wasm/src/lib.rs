// wellen_wasm — WebAssembly bridge to the wellen waveform parser.
//
// Mirrors the desktop wellen_ffi crate method-for-method so that the Dart-side
// WellenWasmProvider matches the WellenProvider (FFI) semantics exactly.
//
// Input: byte buffers (Uint8Array on the JS side). No filesystem access —
// browsers cannot pass file paths, only file contents read via the File API,
// drag-and-drop, or fetch().
//
// Single-threaded: browser WASM threading (SharedArrayBuffer + COOP/COEP) is
// deliberately not used. wellen's parallel VCD parse is the desktop win;
// on the web we accept single-threaded decode in exchange for working without
// cross-origin-isolation deployment headers.
//
// Panic safety: every entry point runs inside `catch_unwind`. Panics become
// structured JsError objects so the Dart side never crashes the isolate.

#![allow(clippy::missing_safety_doc)]
#![allow(clippy::let_and_return)]

use std::collections::{HashMap, HashSet};
use std::io::Cursor;
use std::panic;

use wasm_bindgen::prelude::*;
use wellen::{
    Hierarchy, ScopeRef, ScopeType, SignalRef, TimescaleUnit, VarDirection, VarRef, VarType, simple,
};

// ── file format constants ─────────────────────────────────────────────────────

const FORMAT_UNKNOWN: i32 = 0;
const FORMAT_VCD: i32 = 1;
const FORMAT_FST: i32 = 2;
const FORMAT_GHW: i32 = 3;

// ── module init ───────────────────────────────────────────────────────────────

#[wasm_bindgen(start)]
pub fn init() {
    // Forward Rust panics to console.error with backtraces — invaluable when a
    // panic surfaces during integration testing.
    console_error_panic_hook::set_once();
}

// ── handle ─────────────────────────────────────────────────────────────────────
//
// A WellenWasm holds one open waveform. Unlike the FFI crate where the handle
// is a raw pointer, here we let JS hold a wasm-bindgen-managed reference. The
// JS side calls .free() (auto-generated by wasm-bindgen) when done.

#[wasm_bindgen]
pub struct WellenWasm {
    waveform: simple::Waveform,
    // Pre-computed name strings; indexed by Scope/Var index. Returning them
    // straight as `String` avoids re-deriving every call.
    scope_names: Vec<String>,
    var_names: Vec<String>,
    file_format: i32,
    total_transitions: u64,
    loaded_refs: HashSet<u32>,
    // Cached per-signal change counts (filled on first load).
    signal_change_counts: HashMap<u32, u64>,
}

// ── helpers ───────────────────────────────────────────────────────────────────

fn detect_format(filename: &str) -> i32 {
    match filename
        .rsplit('.')
        .next()
        .unwrap_or("")
        .to_lowercase()
        .as_str()
    {
        "vcd" => FORMAT_VCD,
        "fst" => FORMAT_FST,
        "ghw" => FORMAT_GHW,
        _ => FORMAT_UNKNOWN,
    }
}

fn detect_format_from_bytes(bytes: &[u8]) -> i32 {
    // Magic-byte detection for the binary formats; VCD is ASCII text, so the
    // fallback handles it.
    if bytes.len() >= 8 && &bytes[0..1] == b"\xf2" {
        // FST starts with 0xf2 0xff 0xee... (block-type byte 0xf2).
        return FORMAT_FST;
    }
    if bytes.len() >= 4 && &bytes[0..4] == b"GHDL" {
        // GHW header begins with "GHDL".
        return FORMAT_GHW;
    }
    // VCD starts with text — usually $date or $timescale or $version.
    if bytes.len() >= 8 && (bytes.starts_with(b"$") || bytes.starts_with(b"\n$")) {
        return FORMAT_VCD;
    }
    FORMAT_UNKNOWN
}

